"""Evidence tables and provisional interpretation, with limits next to every effect."""

import json
from pathlib import Path

import pandas as pd

from analysis.memory_audit.design import ENERGY_MODE


def number(value, scale=1):
    return "unavailable" if value is None else f"{value * scale:.4g}"


def write_report(destination: Path) -> None:
    inventory = json.loads((destination / "inventory.json").read_text())
    effects = json.loads((destination / "paired-effects.json").read_text())
    issues = json.loads((destination / "integrity-issues.json").read_text())
    lines = [
        "# Memory Under Interference: Phases1-4 evidence audit",
        "",
        "Status: provisional analysis for owner interpretation review. No new model inference; "
        "E3/MemoryGraph untested. This report does not authorize manuscript conclusions.",
        "",
        "Counts and effects are generated by analysis/memory_audit/run.py. Calls/scores "
        "source folders and keys are in calls.csv and functions.csv; frozen inputs and "
        "hashes are in input-manifest.json. Definitions/labels: "
        "docs/plans/MEMORY_FINAL_AUDIT_2026_11_24.md.",
        "Companion review: REVIEWER_AUDIT.md; full condition tables: CONDITION_TABLES.md.",
        "",
        "## Collection and integrity",
        "",
        "|Stage|Population|Expected|Saved|Score records|API failures|Caps|",
        "|---|---|---:|---:|---:|---:|---:|",
    ]
    for name, record in inventory.items():
        lines.append(
            f"|{name}|{record['phase']}|{record['expected']}|{record['calls']}|"
            f"{record['scores']}|{record['failed_calls']}|{record['caps']}|"
        )
    lines += [
        "",
        f"Native/extraction/measurement integrity issues: {len(issues)}. "
        "Inspect integrity-issues.json; no original values are silently corrected.",
        "",
        "## Registered primary contrasts and registered exploratory M1",
        "",
        "Positive values mean treatment has higher success/adherence than control. "
        "Intervals resample paired tasks; task means retain all registered samples/cells. "
        "M1 intervals/tests are conditional on fixed companions, with unresolved overlap. "
        "A test p-value is not a causal interpretation or an effect-size measure.",
        "",
        "|Stage/model|Comparison|Endpoint|Tasks|Difference pp|95% CI pp|Holm p|Label|",
        "|---|---|---|---:|---:|---|---:|---|",
    ]
    primary = [
        r
        for r in effects
        if r["variant"] == "primary"
        and ("primary" in r["family"] or "registered_exploratory" in r["family"])
    ]
    for r in primary:
        ci = r["ci95"]
        label = r["analysis_label"]
        lines.append(
            f"|{r['stage']}/{r['model']}|{r['name']}|{r['outcome']}|{r['n_units']}|"
            f"{number(r['estimate'], 100)}|"
            f"{', '.join(number(x, 100) for x in ci) if ci else 'unavailable'}|"
            f"{number(r.get('holm_p'))}|{label}|"
        )
    lines += [
        "",
        "## Sensitivity changes",
        "",
        "All secondary variants preserve the primary evidence. Caps are bounded nonpasses; "
        "the optimistic-cap scenario is a bound, not observed repaired success. Removing "
        "caps/drift/short windows changes the paired population. E0 eligibility subset "
        "uses held-out P1 sample0, not the comparison outcome. End/midpoint baseline net "
        "metrics are separate within paired-effects.json, not replacements.",
        "",
        "|Stage/model/comparison|Variant|Primary tasks|Retained tasks|Primary pp|Variant pp|",
        "|---|---|---:|---:|---:|---:|",
    ]
    keyed = {(r["stage"], r["model"], r["name"], r["outcome"]): r for r in primary}
    for r in effects:
        key = (r["stage"], r["model"], r["name"], r["outcome"])
        p = keyed.get(key)
        if p and r["variant"] != "primary":
            if r["n_units"] != p["n_units"] or r["estimate"] != p["estimate"]:
                lines.append(
                    f"|{r['stage']}/{r['model']}/{r['name']}|{r['variant']}|"
                    f"{p['n_units']}|{r['n_units']}|{number(p['estimate'], 100)}|"
                    f"{number(r['estimate'], 100)}|"
                )
    lines += [
        "",
        "## Mechanism and measurement interpretation",
        "",
        "- Cross-pass categories, counts and paired posthoc effects: cross-pass-*.csv/json. "
        "Distractor-only is distinct from both-pass or ordinary both-fail. Isolation and "
        "irrelevant controls address pre-existing distractor success.",
        "- M1: m1-bundle-dependencies.json reports per-function and all-functions outcomes "
        "against component isolation, reused references and graph components. One connected "
        "membership component does not permit a robust independent-component CI.",
        "- R1: r1-prompt-audit.csv records target repetition and preference presence. "
        "Oracle selection is privileged; formatting compaction is not semantic summarization. "
        "Token length/recency/instruction differences preclude a pure memory-policy mechanism.",
        "- E5: e5-format-audit.csv and e5-joint-outcomes.csv retain original adherence. "
        "Fence-tolerant and comment/docstring-free proxies are posthoc, not independent "
        "human assessments of explanation content.",
        "- Partial E4: repeated synthetic probes, not task samples; unmatched repeats are "
        "reported separately. The study is incomplete and constrained decoding changes its "
        "scope. Setup/priming energy is outside measured requests.",
        "",
        "Energy tool/mode: " + ENERGY_MODE + ". Condition totals are available-only and "
        "carry coverage; partial totals cannot be described as full condition costs. "
        "Task bootstrap reflects sampling variation, not sensor calibration. Signed net "
        "values remain signed. Conditions.csv/json include covered-population energy per "
        "correct and its denominator. No-correct ratios are undefined.",
        "",
        "## Interpretation changers and unresolved limits",
        "",
        "Reference/oracle and extraction discrepancies; caps and sandbox policy exclusions; "
        "missingness and selected eligibility; task overlap; instruction/length confounding; "
        "baseline drift/short sampling windows; benchmark exposure; two quantized models "
        "and one CPU. None of the observed contrasts measures cognition, intentional giving "
        "up or internal recognition. MemoryGraph has no evaluated intervention here.",
        "",
        "Before a preprint: review the full effect table, null/reversed contrasts and "
        "sensitivity population changes with the owner; resolve scoring/annotation flags; "
        "complete related-work verification; choose claims supported by these data. "
        "No manuscript or arXiv submission has been prepared by this audit.",
    ]
    (destination / "PHASES_1_4_REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    pd.DataFrame(
        [{k: v for k, v in r.items() if k not in {"metrics", "cell_transitions"}} for r in primary]
    ).to_csv(destination / "primary-effect-table.csv", index=False)

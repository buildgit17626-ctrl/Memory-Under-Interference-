class Metadata(HTMLParser):
    def __init__(self):
        super().__init__()
        self.values = {}

    def handle_starttag(self, tag, attrs):
        values = dict(attrs)
        if tag == "meta":
            key = values.get("name", values.get("property", "")).lower()
            if key and "content" in values:
                self.values.setdefault(key, []).append(html.unescape(values["content"]))


def main() -> None:
    directories()
    rows, bibliography = [], []
    for (
        key,
        url,
        year,
        expected,
        question,
        design,
        contribution,
        overlap,
        distinction,
    ) in REFERENCES:
        path = RELEASE / "literature" / (key + ".html")
        if not path.exists():
            request = urllib.request.Request(
                url, headers={"User-Agent": "Research bibliography audit"}
            )
            with urllib.request.urlopen(request, timeout=60) as response:
                path.write_bytes(response.read())
        parser = Metadata()
        parser.feed(path.read_text(encoding="utf-8"))
        values = parser.values
        titles = values.get("citation_title") or values.get("dc.title") or values.get("og:title")
        if not titles or expected.lower() not in titles[0].lower():
            raise ValueError(f"Primary title does not verify: {key}: {titles}")
        authors = values.get("citation_author") or values.get("dc.creator") or []
        if not authors:
            raise ValueError("Primary authors unavailable: " + key)
        doi = values.get("citation_doi", [None])[0]
        row = {
            "key": key,
            "url": url,
            "title": titles[0],
            "authors": authors,
            "year": year,
            "doi": doi,
            "primary_page_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
            "checked": "2026-11-24",
            "question": question,
            "design": design,
            "contribution": contribution,
            "overlap": overlap,
            "distinction": distinction,
            "metadata_dates": values.get("citation_date", [])
            + values.get("citation_publication_date", []),
        }
        rows.append(row)
        names = authors if len(authors) <= 8 else authors[:3] + ["others"]
        title = titles[0].replace("&", r"\&").replace("_", r"\_")
        kind, extra = PUBLISHED.get(key, ("misc", {}))
        row["verified_publication_fields"] = extra
        bibliography.append(
            "@"
            + kind
            + "{"
            + key
            + ",\n  title = {{"
            + title
            + "}},\n  author = {"
            + " and ".join(names)
            + "},\n  year = {"
            + year
            + "},\n  url = {"
            + url
            + "}"
            + (",\n  doi = {" + doi + "}" if doi else "")
            + "".join(
                ",\n  " + field + " = {" + value + "}"
                for field, value in extra.items()
                if field != "doi" or not doi
            )
            + "\n}\n"
        )
        print(json.dumps({"reference_verified": key, "title": titles[0]}), flush=True)
    save_json(RELEASE / "literature/verified-references.json", rows)
    (RELEASE / "manuscript/references.bib").write_text("\n".join(bibliography), encoding="utf-8")
    lines = [
        "# Primary-source related-work comparison",
        "",
        "Checked 24 November 2026. Focused search, not a systematic review or proof of priority.",
        "",
        "|Publication|Question/design|Main contribution|Overlap|Defensible distinction|",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"|[{r['title']}]({r['url']})|{r['question']}; {r['design']}|"
            f"{r['contribution']}|{r['overlap']}|{r['distinction']}|"
        )
    (RELEASE / "RELATED_WORK.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
